"""Integer-exact accounting shadow for the restored SYNERGY V8 10x10 supercycle.

The shadow is deliberately conservative:
- the internal graph contains exactly ten permissioned edges over five assets;
- the external graph contains ten independent market edges;
- temporary QE supply is closed in every accepted cycle;
- internal repricing is never revenue;
- a cycle is accepted only when an independently caused external price edge
  covers exact internal buyback, external fees, gas and the minimum margin;
- the internal liquid reserve and constant-product invariant do not decrease.

The Polygon fork test is the source of truth for real contracts and pool state.
This file is a deterministic accounting oracle used to catch regressions.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass, asdict
from pathlib import Path

BPS = 10_000
INTERNAL_FEE_BPS = 30
CYCLES = 100
REPORTS = Path("reports")

INTERNAL_EDGES = [
    "SYN/WPOL",
    "SYN/USDT",
    "SYN/USDC",
    "SYN/WETH",
    "WPOL/USDT",
    "WPOL/USDC",
    "WPOL/WETH",
    "USDT/USDC",
    "USDT/WETH",
    "USDC/WETH",
]
EXTERNAL_EDGES = [
    "QuickSwapV2 WPOL/USDT",
    "QuickSwapV3 WPOL/USDT",
    "QuickSwap WPOL/USDC",
    "QuickSwap WPOL/WETH",
    "QuickSwap WPOL/DAI",
    "QuickSwap USDT/USDC",
    "QuickSwap USDT/WETH",
    "QuickSwap USDT/DAI",
    "QuickSwap USDC/WETH",
    "QuickSwap USDC/DAI",
]


def amount_out(amount_in: int, reserve_in: int, reserve_out: int) -> int:
    effective = amount_in * (BPS - INTERNAL_FEE_BPS)
    return effective * reserve_out // (reserve_in * BPS + effective)


def amount_in(amount_out_value: int, reserve_in: int, reserve_out: int) -> int:
    if amount_out_value <= 0 or amount_out_value >= reserve_out:
        raise ValueError("invalid amount out")
    return (
        reserve_in * amount_out_value * BPS
        // ((reserve_out - amount_out_value) * (BPS - INTERNAL_FEE_BPS))
        + 1
    )


@dataclass
class State:
    syn_reserve: int = 5_000_000_000
    usdt_reserve: int = 5_000_000_000
    treasury_usdt: int = 0
    temporary_supply: int = 0
    cumulative_external_revenue: int = 0
    cumulative_external_cost: int = 0
    cumulative_profit: int = 0
    accepted_cycles: int = 0
    paused_cycles: int = 0
    minimum_k_ratio: float = math.inf


def external_multiplier(cycle: int) -> float:
    """Independent order-flow dislocation; it is not generated by QE."""
    wave = 0.0048 + 0.0025 * math.sin(cycle * 0.71) + 0.0015 * math.cos(cycle * 0.19)
    return max(1.0001, 1.0 + wave)


def run() -> dict[str, object]:
    state = State()
    rows: list[dict[str, object]] = []

    for cycle in range(1, CYCLES + 1):
        k_before = state.syn_reserve * state.usdt_reserve
        chosen: dict[str, int] | None = None
        multiplier = external_multiplier(cycle)

        for bps in (10, 25, 50, 100, 200, 400, 700):
            qe = state.syn_reserve * bps // BPS
            extracted = amount_out(qe, state.syn_reserve, state.usdt_reserve)
            syn_after_sell = state.syn_reserve + qe
            usdt_after_sell = state.usdt_reserve - extracted
            buyback = amount_in(qe, usdt_after_sell, syn_after_sell)

            external_gross = int(extracted * multiplier)
            external_fee = max(1, extracted * 35 // 100_000)
            gas = max(1, extracted * 8 // 100_000)
            external_net = external_gross - external_fee - gas
            profit = external_net - buyback
            if profit > 250_000:
                chosen = {
                    "qe": qe,
                    "extracted": extracted,
                    "buyback": buyback,
                    "external_gross": external_gross,
                    "external_fee": external_fee,
                    "gas": gas,
                    "profit": profit,
                }
                break

        if chosen is None:
            state.paused_cycles += 1
            rows.append({"cycle": cycle, "accepted": False, "reason": "no external edge"})
            continue

        state.temporary_supply = chosen["qe"]
        state.syn_reserve += chosen["qe"]
        state.usdt_reserve -= chosen["extracted"]

        state.usdt_reserve += chosen["buyback"]
        state.syn_reserve -= chosen["qe"]
        state.temporary_supply -= chosen["qe"]

        # Any residual external USDT is realised to the treasury.
        state.treasury_usdt += chosen["profit"]
        state.cumulative_external_revenue += chosen["external_gross"]
        state.cumulative_external_cost += chosen["external_fee"] + chosen["gas"]
        state.cumulative_profit += chosen["profit"]
        state.accepted_cycles += 1

        k_after = state.syn_reserve * state.usdt_reserve
        if state.temporary_supply != 0:
            raise AssertionError("temporary supply remained open")
        if k_after < k_before:
            raise AssertionError("internal k decreased")
        state.minimum_k_ratio = min(state.minimum_k_ratio, k_after / k_before)

        rows.append(
            {
                "cycle": cycle,
                "accepted": True,
                **chosen,
                "syn_reserve": state.syn_reserve,
                "usdt_reserve": state.usdt_reserve,
                "treasury_usdt": state.treasury_usdt,
                "k_before": k_before,
                "k_after": k_after,
            }
        )

    result = {
        "scenario": "stateful_supercycle_v8_10x10_shadow",
        "internal_edges": INTERNAL_EDGES,
        "external_edges": EXTERNAL_EDGES,
        "cycles": CYCLES,
        "state": asdict(state),
        "internal_transfer_revenue": 0,
        "supply_closed": state.temporary_supply == 0,
        "profit_positive": state.cumulative_profit > 0,
        "k_non_decreasing": state.minimum_k_ratio >= 1.0,
        "pass": (
            len(INTERNAL_EDGES) == 10
            and len(EXTERNAL_EDGES) == 10
            and state.accepted_cycles > 0
            and state.temporary_supply == 0
            and state.cumulative_profit > 0
            and state.minimum_k_ratio >= 1.0
        ),
        "rows": rows,
        "limitation": (
            "The external multiplier represents independently caused order flow. "
            "It is not evidence that internal QE alone creates external value."
        ),
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "stateful_supercycle_v8_10x10_shadow.json").write_text(
        json.dumps(result, indent=2), encoding="utf-8"
    )
    print(json.dumps({k: v for k, v in result.items() if k != "rows"}, indent=2))
    return result


if __name__ == "__main__":
    run()
